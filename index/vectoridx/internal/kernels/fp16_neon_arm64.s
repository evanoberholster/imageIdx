// func l2Float16NEON(a, b []byte) float32
// Processes floor(len(a)/64) blocks of 32 binary16 values. Two vectors are
// converted together so each branch covers 64 bytes. FMLAL/FMLAL2 variants
// were measured slower than this FCVTL + FP32 FMA path on Apple M4.
TEXT ·l2Float16NEON(SB), NOSPLIT, $0-52
	MOVD a_base+0(FP), R0
	MOVD a_len+8(FP), R1
	MOVD b_base+24(FP), R2
	LSR  $6, R1, R3
	VEOR V0.B16, V0.B16, V0.B16
	VEOR V1.B16, V1.B16, V1.B16
	VEOR V2.B16, V2.B16, V2.B16
	VEOR V3.B16, V3.B16, V3.B16
	VEOR V4.B16, V4.B16, V4.B16
	VEOR V5.B16, V5.B16, V5.B16
	VEOR V6.B16, V6.B16, V6.B16
	VEOR V7.B16, V7.B16, V7.B16
	CBZ  R3, done
loop:
	VLD1.P 64(R0), [V8.H8, V9.H8, V10.H8, V11.H8]
	VLD1.P 64(R2), [V12.H8, V13.H8, V14.H8, V15.H8]
	// a: V8->V16,V17; V9->V18,V19; V10->V20,V21; V11->V22,V23
	WORD $0x0e217910
	WORD $0x4e217911
	WORD $0x0e217932
	WORD $0x4e217933
	WORD $0x0e217954
	WORD $0x4e217955
	WORD $0x0e217976
	WORD $0x4e217977
	// b: V12->V24,V25; V13->V26,V27; V14->V28,V29; V15->V30,V31
	WORD $0x0e217998
	WORD $0x4e217999
	WORD $0x0e2179ba
	WORD $0x4e2179bb
	WORD $0x0e2179dc
	WORD $0x4e2179dd
	WORD $0x0e2179fe
	WORD $0x4e2179ff
	VFSUB V24.S4, V16.S4, V16.S4
	VFSUB V25.S4, V17.S4, V17.S4
	VFSUB V26.S4, V18.S4, V18.S4
	VFSUB V27.S4, V19.S4, V19.S4
	VFSUB V28.S4, V20.S4, V20.S4
	VFSUB V29.S4, V21.S4, V21.S4
	VFSUB V30.S4, V22.S4, V22.S4
	VFSUB V31.S4, V23.S4, V23.S4
	VFMLA V16.S4, V16.S4, V0.S4
	VFMLA V17.S4, V17.S4, V1.S4
	VFMLA V18.S4, V18.S4, V2.S4
	VFMLA V19.S4, V19.S4, V3.S4
	VFMLA V20.S4, V20.S4, V4.S4
	VFMLA V21.S4, V21.S4, V5.S4
	VFMLA V22.S4, V22.S4, V6.S4
	VFMLA V23.S4, V23.S4, V7.S4
	SUBS $1, R3, R3
	BNE  loop
done:
	VFADD V1.S4, V0.S4, V0.S4
	VFADD V3.S4, V2.S4, V2.S4
	VFADD V5.S4, V4.S4, V4.S4
	VFADD V7.S4, V6.S4, V6.S4
	VFADD V2.S4, V0.S4, V0.S4
	VFADD V6.S4, V4.S4, V4.S4
	VFADD V4.S4, V0.S4, V0.S4
	VFADDP V0.S4, V0.S4, V0.S4
	VFADDP V0.S4, V0.S4, V0.S4
	FMOVS F0, ret+48(FP)
	RET

