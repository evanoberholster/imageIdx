//go:build amd64

#include "textflag.h"

// func dotAVX2(a, b []byte) float32
// Processes floor(len(a)/128) blocks of 32 floats. The Go wrapper handles the
// scalar tail and the no-AVX2 case.
TEXT ·dotAVX2(SB), NOSPLIT, $0-52
	MOVQ a_base+0(FP), AX
	MOVQ a_len+8(FP), CX
	MOVQ b_base+24(FP), BX
	SHRQ $7, CX
	TESTQ CX, CX
	JZ   done
	VXORPS Y0, Y0, Y0
	VXORPS Y1, Y1, Y1
	VXORPS Y2, Y2, Y2
	VXORPS Y3, Y3, Y3
loop:
	VMOVUPS (AX), Y4
	VMOVUPS 32(AX), Y5
	VMOVUPS 64(AX), Y6
	VMOVUPS 96(AX), Y7
	VMOVUPS (BX), Y8
	VMOVUPS 32(BX), Y9
	VMOVUPS 64(BX), Y10
	VMOVUPS 96(BX), Y11
	VMULPS Y8, Y4, Y12
	VMULPS Y9, Y5, Y13
	VMULPS Y10, Y6, Y14
	VMULPS Y11, Y7, Y15
	VADDPS Y12, Y0, Y0
	VADDPS Y13, Y1, Y1
	VADDPS Y14, Y2, Y2
	VADDPS Y15, Y3, Y3
	ADDQ $128, AX
	ADDQ $128, BX
	DECQ CX
	JNZ  loop
	VADDPS Y1, Y0, Y0
	VADDPS Y3, Y2, Y2
	VADDPS Y2, Y0, Y0
	VEXTRACTF128 $1, Y0, X1
	VADDPS X1, X0, X0
	VHADDPS X0, X0, X0
	VHADDPS X0, X0, X0
	MOVSS X0, ret+48(FP)
	VZEROUPPER
	RET
done:
	VXORPS X0, X0, X0
	MOVSS X0, ret+48(FP)
	VZEROUPPER
	RET

